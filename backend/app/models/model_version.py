"""ML model version registry, and the audit trail for changes to it.

WHY A REGISTRY AND NOT JUST A FOLDER OF FILES.

The pre-existing console could import an artifact and make it active, but it had
nowhere to record that the file had been *checked* or *when it last worked*. That
left two gaps this prompt asks to close:

 1. "Which model is deployed, what version is it, and when was it last updated?"
     had to be answered by reading a filename and a modification time on a disk
     nobody browsing the console can see.
 2. Rolling back was impossible to do safely, because nothing recorded which
     versions had ever been *validated*. Activating any file that happened to be
     present could activate one that had never run.

So each accepted artifact gets a row here, carrying its own checksum, the
validation verdict, and the lifecycle state. The ACTIVATION itself is still the
single pointer the existing `model_service` writes — this table records history
around that pointer, it does not replace it, so every existing behaviour and every
existing route keeps working exactly as before.

STATE MACHINE, and the one rule that matters:

    registered -> validating -> validated | rejected
                              validated  -> active  -> superseded
                              active     -> rolled_back

A model can only move to `active` FROM `validated`. There is no code path that
sets an unvalidated artifact active, and `promote_active_model` refuses to
promote anything whose own recorded validation did not pass. That is what makes
requirement "preserve the active model if validation or deployment fails" a
property of the schema rather than a thing every future caller has to remember.

NOTHING DERIVED FROM A CREDENTIAL IS STORED, and no secret is stored at all: an
artifact path is a filesystem location under the configured model directory, and
an audit row names the console identity that acted, never a token or a password.
"""

import json

from app.extensions import db
from app.models.mixins import SerializableMixin, TimestampMixin, utcnow


def _safe_json(raw: str | None, default):
    if not raw:
        return default
    try:
        parsed = json.loads(raw)
    except (TypeError, ValueError):
        return default
    return parsed if isinstance(parsed, type(default)) else default


# --- The lifecycle, in one place so no route invents a fifth state ----------

#: Accepted from the server, not from the client. A request that names anything
#: else is refused rather than stored.
STATUSES = (
    "registered",  # artifact stored, not yet checked
    "validating",  # a validation subprocess is running against it
    "validated",   # passed every compatibility and schema check
    "rejected",    # failed one, with the reason recorded
    "active",      # currently answering predictions
    "superseded",  # was active, has been replaced by a newer one
    "rolled_back", # was active, was replaced by an older known-good one
)

#: The one transition into `active`, and the only state it may come from. Kept
#: as data so `promote_active_model` and the audit view cannot disagree.
ACTIVATABLE_FROM = frozenset({"validated"})

#: The actions the audit log records. An action outside this set is refused, so
#: the log cannot accumulate entries nothing knows how to read.
ACTIONS = (
    "register",     # an artifact was uploaded and stored
    "validate",     # a validation run was started
    "activate",     # a validated artifact became the active one
    "rollback",     # the active pointer moved back to an earlier version
    "supersede",    # a previously active artifact was replaced
    "reject",       # validation failed and the artifact is not usable
    "delete",       # a registered-but-inactive artifact was removed
)


class ModelVersion(TimestampMixin, SerializableMixin, db.Model):
    """One registered model artifact and everything known about it."""

    __tablename__ = "model_versions"

    id = db.Column(db.Integer, primary_key=True)

    # The administrator-supplied version string, e.g. "rf-2026-04-a". Unique, so
    # the same version cannot be registered twice and quietly become two rows
    # that both look authoritative.
    version = db.Column(db.String(120), unique=True, nullable=False, index=True)

    # A human label for the row. Never used as a path component.
    display_name = db.Column(db.String(190), nullable=True)

    # The filename INSIDE the import directory, and where the artifact lives on
    # disk. Both are server-generated by `_safe_name`, never taken from the
    # upload as-is: the upload's filename is attacker-controlled and
    # `../../app.py` must not be reachable from this column.
    filename = db.Column(db.String(255), nullable=False)
    artifact_path = db.Column(db.String(512), nullable=False)

    size_bytes = db.Column(db.BigInteger, nullable=True)
    # SHA-256 of the file's bytes, lowercase hex. Computed once at import over
    # the STORED file, so it describes what is on disk rather than what the
    # client said it sent.
    checksum_sha256 = db.Column(db.String(64), nullable=True, index=True)

    # The upload's declared media type and its filename, kept for the audit view
    # only. Neither is trusted for validation - the extension and the bytes are
    # what decide.
    original_filename = db.Column(db.String(255), nullable=True)
    content_type = db.Column(db.String(120), nullable=True)

    # `app.constants.FEATURE_NAMES` at import time, and the classes the artifact
    # declares. Stored so the console can SHOW the contract a model was built
    # against without loading it again, and so a later constants change is
    # detectable against a model registered before it.
    feature_schema = db.Column(db.Text, nullable=True)
    label_schema = db.Column(db.Text, nullable=True)

    # What the artifact itself claims: its own version string and training
    # timestamp, when it is an envelope with those keys.
    declared_version = db.Column(db.String(120), nullable=True)
    trained_at = db.Column(db.String(64), nullable=True)

    # Library versions that produced the artifact. Recorded because a model
    # trained on a different scikit-learn major is a real compatibility risk and
    # the only way to know is to have kept the number.
    scikit_learn_version = db.Column(db.String(40), nullable=True)
    numpy_version = db.Column(db.String(40), nullable=True)

    status = db.Column(db.String(24), nullable=False, default="registered", index=True)

    # Whether validation passed, and why it did not. Both JSON:
    #   passed  -> {"checks": [{"name", "ok", "detail"}], "features": [...], ...}
    #   failed  -> {"checks": [...], "failure": "<what actually failed>"}
    validation_report = db.Column(db.Text, nullable=True)
    validated_at = db.Column(db.DateTime, nullable=True)
    # Who ran it. The console identity, never an IP or a token.
    validated_by = db.Column(db.String(190), nullable=True)

    # The console identity that registered and last activated this artifact.
    registered_by = db.Column(db.String(190), nullable=True)
    activated_at = db.Column(db.DateTime, nullable=True)
    activated_by = db.Column(db.String(190), nullable=True)

    # The NOTE an admin attaches when registering, so a registry of "v1, v2, v3"
    # still says which was the recall fix.
    notes = db.Column(db.String(500), nullable=True)

    _serializable_fields = (
        "id",
        "version",
        "display_name",
        "filename",
        "size_bytes",
        "checksum_sha256",
        "original_filename",
        "status",
        "declared_version",
        "trained_at",
        "scikit_learn_version",
        "numpy_version",
        "registered_by",
        "validated_by",
        "validated_at",
        "activated_by",
        "activated_at",
        "notes",
    )
    _serializable_datetime_fields = ("created_at", "updated_at", "validated_at", "activated_at")

    def get_feature_schema(self) -> list[str]:
        return _safe_json(self.feature_schema, [])

    def set_feature_schema(self, value) -> None:
        self.feature_schema = json.dumps(list(value or []))

    def get_label_schema(self) -> list[str]:
        return _safe_json(self.label_schema, [])

    def set_label_schema(self, value) -> None:
        self.label_schema = json.dumps([str(item) for item in (value or [])])

    def get_validation_report(self) -> dict:
        return _safe_json(self.validation_report, {})

    def set_validation_report(self, value: dict) -> None:
        self.validation_report = json.dumps(value or {})

    @property
    def validated(self) -> bool:
        """Whether THIS ROW's own recorded validation PASSED.

        Deliberately NOT the same test as "is this row's status `validated`". A
        row that passed validation and has since been superseded or rolled back
        has not stopped being validated - it is still a perfectly good rollback
        target, and refusing it would make rolling back impossible, which is the
        one thing a rollback exists to do.

        So this reads the STORED REPORT, which is immutable evidence of the one
        run that happened. The status is a pointer's position in the lifecycle;
        the report is the fact. A model can only become active on the strength of
        the fact, never the pointer.
        """
        return bool(self.get_validation_report().get("passed"))

    def to_dict(self) -> dict:
        payload = super().to_dict()
        report = self.get_validation_report()
        payload["features"] = self.get_feature_schema()
        payload["labels"] = self.get_label_schema()
        payload["validation_passed"] = self.validated
        payload["validation"] = report
        return payload

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<ModelVersion {self.version} status={self.status}>"


class ModelAuditLog(TimestampMixin, SerializableMixin, db.Model):
    """One row per attempted change to the model registry. Append-only.

    Requirement 9 asks for the admin identity, the model version, a timestamp,
    the action and the outcome. Every one of those is a column here.

    FAILED ATTEMPTS ARE RECORDED, which is the point of a log rather than a
    counter: "someone tried to activate a model that failed validation" is exactly
    the event nobody wants discovered from the behaviour of a running system
    instead. There is deliberately no UPDATE or DELETE path on this table.

    NO SECRET IS STORED. `detail` holds a short human explanation; it is never
    populated with a credential, an API key or a stack trace containing one.
    """

    __tablename__ = "model_audit_logs"

    id = db.Column(
        # A BIGINT primary key, matching `login_events`, because this log will
        # outgrow the other tables eventually. The variant is load-bearing on
        # SQLite: SQLite only auto-increments a column declared exactly
        # `INTEGER PRIMARY KEY`, so a bare BigInteger there is created as a plain
        # integer column and every insert fails with a NOT NULL error on `id`.
        # The variant keeps the production schema BIGINT and still works on
        # SQLite, which is what makes this table testable at all.
        db.BigInteger().with_variant(db.Integer, "sqlite"),
        primary_key=True,
        autoincrement=True,
    )

    # The console identity that acted - the same value the rest of the console
    # audits with.
    actor = db.Column(db.String(190), nullable=False, index=True)

    # The version the action concerned. Kept as a plain string rather than a
    # foreign key, so a log line survives the row it refers to being deleted.
    model_version = db.Column(db.String(120), nullable=True, index=True)

    action = db.Column(db.String(32), nullable=False, index=True)
    success = db.Column(db.Boolean, nullable=False, default=False)
    # Short explanation of a failure, or a one-line summary of a success. Never a
    # credential and never a raw traceback.
    detail = db.Column(db.String(500), nullable=True)

    # What was active BEFORE and AFTER the action, so a rollback is legible from
    # the log alone without having to reconstruct it from version ordering.
    previous_active = db.Column(db.String(120), nullable=True)
    resulting_active = db.Column(db.String(120), nullable=True)

    occurred_at = db.Column(db.DateTime, default=utcnow, nullable=False, index=True)

    _serializable_fields = (
        "id",
        "actor",
        "model_version",
        "action",
        "success",
        "detail",
        "previous_active",
        "resulting_active",
    )
    _serializable_datetime_fields = ("occurred_at",)

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return (
            f"<ModelAuditLog {self.action} v={self.model_version} "
            f"ok={self.success} by {self.actor}>"
        )
