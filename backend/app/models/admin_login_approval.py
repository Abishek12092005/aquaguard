"""Admin login approval requests — one row per sign-in attempt awaiting a decision.

WHY THIS IS A TABLE AND NOT A FIELD ON `admin_settings`.

The pre-existing workflow stored a single pending confirmation in a JSON column,
which is a design with one serious property and one serious gap:

  * ONE PENDING REQUEST AT A TIME. A second sign-in attempt overwrote the first,
    so two administrators (or one administrator on two devices) could not both be
    waiting, and answering the newer mail silently invalidated the older one.
  * THE TOKEN WAS THE ENTIRE AUTHORISATION. `confirm_unlock` accepted a bearer
    token from a GET link. Any link-scanner, mail proxy or browser prefetch that
    opened that URL - which is the normal behaviour of most of them - consumed a
    single-use credential and made the decision. A security control that fires
    when an automated scanner touches it is not a security control.

Each attempt is a ROW here, so attempts are independent and each is answered on
its own terms.

THE BINDING, WHICH IS THE WHOLE OF REQUIREMENT 10. A decision is only accepted
when ALL of these match the row:

  * the action token, compared in constant time - this is the mail's authority;
  * the exact row, so one mail cannot answer another attempt;
  * the stored challenge, so the decision is bound to the browser that asked;
  * an unexpired, undecided, unconsumed request.

The challenge is generated by the BACKEND, handed to the login page once, and
stored server-side in the browser's `sessionStorage`. It is NOT a cookie and NOT
a URL parameter. That is deliberate: a cookie would be sent by any cross-site
request (CSRF), and a URL parameter would leak into `Referer` headers, into proxy
and server logs, and into the browser history - and a security-scanner that
follows URLs would receive it along with everyone else.

# WHAT IS NEVER STORED HERE. No password, no password hash, no console
credential, and no mail token in a URL. The requester identity is the
console's own username, already verified by the caller before this row was
created.

THE PLAIN TOKEN IS NEVER STORED. `action_token_hash` is the only copy the
database holds. The clear token lives in the approval mail and nowhere else,
which is why the review page can echo it back into its buttons without the
server needing a recoverable copy - and why a database dump yields no usable
approval credential.
"""

import secrets
from datetime import datetime, timezone

from app.extensions import db
from app.models.mixins import SerializableMixin, TimestampMixin, utcnow

# The decision states. A row is created `pending` and moves once.
STATUS_PENDING = "pending"
STATUS_APPROVED = "approved"
STATUS_DENIED = "denied"
STATUS_EXPIRED = "expired"
STATUS_CONSUMED = "consumed"

# The actions the mail can ask for.
ACTION_APPROVE = "approve"
ACTION_DENY = "deny"


def _utcnow_naive() -> datetime:
    """Timezone-NAIVE UTC now, for comparing with columns read back from a DB.

    MySQL and SQLite both return naive datetimes: the driver has no way to know
    the server's timezone policy, so `DATETIME`/`TIMESTAMP` columns arrive without
    a `tzinfo`. Comparing such a value against an aware `datetime.now(timezone.utc)`
    raises `TypeError` — naive vs aware cannot be compared — which is exactly what
    the first live run hit on the review page.

    Every stored timestamp in this table is written UTC, so a naive-UTC comparison
    is correct; this exists to make that choice explicit at every site that needs
    it rather than to silently paper over a timezone question.
    """
    return datetime.now(timezone.utc).replace(tzinfo=None)


def _aware(value: datetime | None) -> datetime | None:
    """Re-attach UTC to a naive datetime read from the database.

    The inverse of the above, for the places that return a timestamp to a client:
    the stored value is UTC by construction, so labelling it UTC is a correction,
    not an assumption. Passing through an already-aware value unchanged means this
    is safe on backends whose drivers do return aware datetimes.
    """
    if value is None:
        return None
    return value if value.tzinfo is not None else value.replace(tzinfo=timezone.utc)


def new_token() -> str:
    """A 256-bit single-use token, URL-safe.

    `token_urlsafe(32)` is 32 bytes of `secrets` entropy - 256 bits, which is not
    a guessable number. It is compared with `hmac.compare_digest` everywhere it
    is read, so a mismatch takes the same time regardless of how many characters
    matched.
    """
    return secrets.token_urlsafe(32)


class AdminLoginApproval(TimestampMixin, SerializableMixin, db.Model):
    """One sign-in attempt waiting on an emailed decision."""

    __tablename__ = "admin_login_approvals"

    id = db.Column(db.BigInteger().with_variant(db.Integer, "sqlite"), primary_key=True)

    # The row's own opaque id, returned to the login page as the request handle.
    # It identifies WHICH attempt is being polled; it is not the authority to
    # decide it - only the mail's action token is.
    request_id = db.Column(db.String(64), unique=True, nullable=False, index=True, default=lambda: new_token())

    # --- What was verified BEFORE this row existed ---------------------------
    # The console username, already checked against the credential. Stored so the
    # mail can name who is asking, and so the audit row means something.
    admin_username = db.Column(db.String(190), nullable=False)

    # --- The bindings from requirement 10 -----------------------------------
    #
    # Both are SHA-256 hex digests and both are stored INSTEAD OF the value.
    # They are secrets in exactly the way a password is: a database dump, a log
    # line or a support screenshot must not hand over a working approval.
    #
    #   action_token_hash — the MAIL's authority: single-use, short-lived, and
    #     required again at unlock time so an approval cannot be spent later by
    #     whoever finds the request id.
    action_token_hash = db.Column(db.String(64), nullable=False, index=True)
    #   challenge_hash — ties the DECISION to the BROWSER that asked. The clear
    #     value never leaves the login page, so it cannot leak through a URL, a
    #     Referer header, a proxy log or the browser history.
    challenge_hash = db.Column(db.String(64), nullable=False)
    # Ties the REQUEST to the attempt, so a token minted for one attempt cannot
    # be used to answer another even if both are in flight.
    attempt_nonce = db.Column(db.String(64), nullable=False)

    # --- Request context shown in the mail -----------------------------------
    requested_at = db.Column(db.DateTime, default=utcnow, nullable=False, index=True)
    ip_address = db.Column(db.String(45), nullable=True)
    user_agent = db.Column(db.String(255), nullable=True)
    # A short, non-identifying label for the browser, so the admin recognises
    # their own machine at a glance.
    device_label = db.Column(db.String(120), nullable=True)
    # Whether the credentials supplied were syntactically complete. Recorded for
    # the audit trail; the password itself is NEVER stored in any form.
    credential_shape = db.Column(db.String(40), nullable=True)

    # --- Decision -------------------------------------------------------------
    status = db.Column(db.String(20), nullable=False, default=STATUS_PENDING, index=True)
    expires_at = db.Column(db.DateTime, nullable=False, index=True)
    decided_at = db.Column(db.DateTime, nullable=True)
    decided_by = db.Column(db.String(190), nullable=True)
    # Why a decision was refused, for the audit trail. Never a token.
    decision_detail = db.Column(db.String(500), nullable=True)
    # Set once the decision has been SPENT, which is what makes it single-use
    # even if the row is somehow re-read.
    consumed_at = db.Column(db.DateTime, nullable=True)

    _serializable_fields = (
        "id",
        "request_id",
        "admin_username",
        "status",
        "requested_at",
        "expires_at",
        "decided_at",
        "device_label",
    )
    _serializable_datetime_fields = ("created_at", "updated_at")

    # The state machine is enforced by a CHECK constraint on the column below, so
    # a row cannot hold a status nothing knows how to interpret.
    __table_args__ = (
        db.CheckConstraint(
            "status IN ('pending', 'approved', 'denied', 'expired', 'consumed')",
            name="ck_admin_login_approvals_status",
        ),
    )

    def is_pending(self) -> bool:
        """Whether this request can still be answered.

        Expiry is evaluated here rather than by a scheduled job, so a request
        whose moment has passed is refused the instant it is presented - there is
        no window in which an expired row is still actionable because a cleanup
        task has not run yet.
        """
        return self.status == STATUS_PENDING and self.expires_at > _utcnow_naive()

    def to_dict(self) -> dict:
        payload = super().to_dict()
        expired = self.status == STATUS_PENDING and self.expires_at <= _utcnow_naive()
        payload["expired"] = expired
        payload["seconds_remaining"] = (
            0 if expired else max(0, int((self.expires_at - _utcnow_naive()).total_seconds()))
        )
        return payload

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<AdminLoginApproval {self.request_id} {self.status}>"
